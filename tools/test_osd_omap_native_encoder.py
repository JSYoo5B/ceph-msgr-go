"""Checks native OMAP fixture boundaries independently of the Go codecs.

Reference bytes are generated by fresh pinned Ceph native objects. These tests
parse only their raw contract fields; no test generates a Go reference payload.
"""
import hashlib
import json
import pathlib
import struct
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA = ROOT / "internal/osd/testdata"
COMMIT = "7f793731f1b39eb4f465e960113d2363c311b964"


def fixture(name, segment):
    return bytes.fromhex((DATA / (name + "." + segment + ".hex")).read_text())


def read_blob(raw, position):
    if position + 4 > len(raw):
        raise ValueError("short length")
    size = struct.unpack_from("<I", raw, position)[0]
    position += 4
    if size > len(raw) - position:
        raise ValueError("short bytes")
    return raw[position:position + size], position + size


def collection(raw, values, more):
    if len(raw) < 4:
        raise ValueError("short count")
    count = struct.unpack_from("<I", raw)[0]
    if count > len(raw) // 4:
        raise ValueError("impossible count")
    entries, position = [], 4
    for _ in range(count):
        key, position = read_blob(raw, position)
        value = None
        if values:
            value, position = read_blob(raw, position)
        if entries and entries[-1][0] >= key:
            raise ValueError("noncanonical keys")
        entries.append((key, value))
    suffix = None
    if more:
        if position >= len(raw) or raw[position] not in (0, 1):
            raise ValueError("missing/invalid more")
        suffix = bool(raw[position])
        position += 1
    if position != len(raw):
        raise ValueError("trailing collection bytes")
    return entries, suffix


def request_operations(front):
    # v6 client_inc/epoch/flags/mtime/reassert prefix, then native locator
    # struct, PG, object, count. Input vector envelopes are each 38 bytes.
    position = 32
    if front[position:position + 2] != bytes((6, 3)):
        raise ValueError("unexpected locator version")
    size = struct.unpack_from("<I", front, position + 2)[0]
    position += 6 + size + 17
    name, position = read_blob(front, position)
    count = struct.unpack_from("<H", front, position)[0]
    position += 2
    ops = []
    for _ in range(count):
        if position + 38 > len(front):
            raise ValueError("short operation")
        code, flags = struct.unpack_from("<HI", front, position)
        offset, length = struct.unpack_from("<QQ", front, position + 6)
        if front[position + 22:position + 34] != bytes(12):
            raise ValueError("nonzero trailing union")
        payload = struct.unpack_from("<I", front, position + 34)[0]
        ops.append((code, flags, offset, length, payload))
        position += 38
    return name, ops


class NativeOmapCodecFixtures(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.proof = json.loads((DATA / "omap-native-provenance.json").read_text())

    def test_native_source_and_segment_receipts_are_fresh(self):
        self.assertEqual(self.proof["ceph_commit"], COMMIT)
        for field in ("native_payload_encoder_verified", "native_payload_decoder_verified",
                      "native_message_header_verified"):
            self.assertIs(self.proof[field], True)
        for field, source in (("wrapper_sha256", "tools/osd_omap_native_encoder.cc"),
                              ("build_driver_sha256", "tools/osd_omap_native_encoder.py")):
            self.assertEqual(self.proof[field], hashlib.sha256((ROOT / source).read_bytes()).hexdigest())
        for name, recorded in self.proof["fixtures"].items():
            for segment in ("front", "data", "header"):
                raw = fixture(name, segment)
                self.assertEqual(len(raw), recorded[segment + "_bytes"])
                self.assertEqual(hashlib.sha256(raw).hexdigest(), recorded[segment + "_sha256"])
            self.assertEqual(recorded["native_header"]["front_len"], len(fixture(name, "front")))
            self.assertEqual(recorded["native_header"]["data_len"], len(fixture(name, "data")))

    def test_native_request_count_limit_prefix_and_key_bytes(self):
        name = "omap-native-request-v6-read-all"
        front, data = fixture(name, "front"), fixture(name, "data")
        self.assertEqual(struct.unpack_from("<IIIII", front), (1, 11, 0x4000014, 0, 0))
        object_name, operations = request_operations(front)
        self.assertEqual(object_name, b"omap-codec")
        self.assertEqual(operations, [(0x1211, 0, 0, 12, 12), (0x1211, 0, 0, 15, 15),
                                      (0x1212, 0, 0, 22, 22), (0x1214, 0, 0, 26, 26)])
        self.assertEqual(len(data), 75)
        zero_page, next_page, filtered_page, bykeys = data[:12], data[12:27], data[27:49], data[49:]
        self.assertEqual(zero_page, bytes(12))
        cursor, pos = read_blob(next_page, 0)
        self.assertEqual((cursor, struct.unpack_from("<Q", next_page, pos)[0]), (b"a\0\xff", 2))
        cursor, pos = read_blob(filtered_page, 0)
        limit = struct.unpack_from("<Q", filtered_page, pos)[0]
        prefix, end = read_blob(filtered_page, pos + 8)
        self.assertEqual((cursor, limit, prefix, end), (b"a\0\xff", 2, b"b\0\x80", 22))
        # Distinct cursor/prefix catches use of the pinned optional-overload typo.
        self.assertEqual(collection(bykeys, False, False),
                         ([(b"", None), (b"a\0\xff", None), (b"b\x80", None), (b"z", None)], None))

    def test_native_reply_output_boundaries_and_more(self):
        mixed = self.proof["fixtures"]["omap-native-reply-v6-read-mixed"]["decoded_operations"]
        outputs = [bytes.fromhex(op["outdata_hex"]) for op in mixed]
        self.assertEqual(b"".join(outputs), fixture("omap-native-reply-v6-read-mixed", "data"))
        self.assertEqual([op["result"] for op in mixed], [0, 0, 0, 0])
        self.assertEqual([op["payload_len"] for op in mixed], list(map(len, outputs)))
        self.assertEqual(collection(outputs[0], False, True), ([], True))
        self.assertEqual(collection(outputs[1], False, True),
                         ([(b"b\0\x80x", None), (b"b\0\x80y", None)], True))
        self.assertEqual(collection(outputs[2], True, True), ([(b"b\0\x80x", b"\0\xffA\n")], True))
        self.assertEqual(collection(outputs[3], True, False),
                         ([(b"a\0\xff", b""), (b"b\x80", b"\0\xffA\n")], None))
        self.assertEqual(collection(fixture("omap-native-reply-v6-keys-final", "data"), False, True),
                         ([(b"a\0\xff", None), (b"b\x80", None)], False))
        self.assertEqual(collection(fixture("omap-native-reply-v6-vals-empty", "data"), True, True),
                         ([], False))
        self.assertEqual(collection(fixture("omap-native-reply-v6-bykeys-empty-value", "data"), True, False),
                         ([(b"a\0\xff", b"")], None))

    def test_suffix_shapes_are_not_interchangeable(self):
        vals = fixture("omap-native-reply-v6-vals-empty", "data")
        bykeys = fixture("omap-native-reply-v6-bykeys-empty-value", "data")
        for raw, values, more in ((vals[:-1], True, True), (vals, True, False),
                                  (bykeys, True, True), (bykeys + b"\0", True, False)):
            with self.subTest(raw=raw.hex(), more=more):
                with self.assertRaises(ValueError):
                    collection(raw, values, more)


if __name__ == "__main__":
    unittest.main()
